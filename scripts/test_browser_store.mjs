import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const source=readFileSync('lotto/workspace_browser_store.py','utf8').match(/STORE_JS = """([\s\S]*?)"""/)[1];
const render=new Function(source.replace('export default function','return function'))();
const memory=new Map();
globalThis.document={createElement:()=>({style:{},textContent:''})};
globalThis.localStorage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const parent={replaceChildren:()=>{}};
let restored;
const setStateValue=(k,v)=>{restored=v;};
const legacy={id:'purchase-1',updated_at:'2026-10-31T10:00:00+00:00',status:'purchased'};
memory.set('lotto-lab-purchases-v1',JSON.stringify([legacy]));
render({data:{ready:false,nonce:'first'},parentElement:parent,setStateValue});
assert.equal(restored.workspace.purchases[0].id,'purchase-1');
const saved={version:2,purchases:[legacy],recommendations:[{id:'rec-1',created_at:'2026-11-01T00:00:00+00:00'}],notes:[{id:'note-1',created_at:'2026-11-01T00:00:00+00:00'}]};
render({data:{ready:true,nonce:'first',workspace:saved},parentElement:parent,setStateValue});
render({data:{ready:false,nonce:'second'},parentElement:{replaceChildren:()=>{}},setStateValue});
assert.equal(restored.workspace.recommendations.length,1);
assert.equal(restored.workspace.notes.length,1);
saved.purchases=[{...legacy,updated_at:'2026-11-01T11:00:00+00:00',status:'void'}];
render({data:{ready:true,nonce:'second',workspace:saved},parentElement:parent,setStateValue});
render({data:{ready:true,nonce:'first',workspace:{version:2,purchases:[legacy],recommendations:[],notes:[]}},parentElement:parent,setStateValue});
const merged=JSON.parse(memory.get('lotto-lab-workspace-v2'));
assert.equal(merged.purchases[0].status,'void');
assert.equal(merged.recommendations.length,1);
assert.equal(merged.notes.length,1);
globalThis.localStorage={getItem:()=>{throw Error('blocked');}};
render({data:{ready:false,nonce:'blocked'},parentElement:{replaceChildren:()=>{}},setStateValue});
assert.equal(restored.error,true);
console.log('PASS: v1 migration, v2 full history restore, merge, cancellation, blocked storage');
